// Package report writes the human-facing views: one markdown file per
// vulnerability (alerts/YYYY/yyyy-mm-dd-tech-slug.md) and a digest of open work.
// Files are generated from the store, which stays the source of truth.
package report

import (
	"fmt"
	"path/filepath"
	"strings"

	"cvewatch/src/fsx"
	"cvewatch/src/model"
	"cvewatch/src/query"
)

// Path is stable for a vulnerability: it only uses the first-seen date and
// the techs frozen at evaluation, so later config edits never move files.
func Path(alertsDir string, v *model.Vulnerability) string {
	tech := "deps"
	if len(v.Techs) > 0 {
		tech = v.Techs[0]
	}
	day := v.FirstSeen.UTC().Format("2006-01-02")
	name := fmt.Sprintf("%s-%s-%s.md", day, slug(tech), slug(v.ID))
	return filepath.Join(alertsDir, v.FirstSeen.UTC().Format("2006"), name)
}

func slug(s string) string {
	s = strings.ToLower(s)
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' {
			return r
		}
		return '-'
	}, s)
}

// Write renders and stores the report, returning its path.
func Write(alertsDir string, v *model.Vulnerability, fs []model.Finding) (string, error) {
	p := Path(alertsDir, v)
	return p, fsx.WriteAtomic(p, []byte(Render(v, fs)))
}

// Render builds the markdown: description, links to the originals, status
// table and a rollout plan per project.
func Render(v *model.Vulnerability, fs []model.Finding) string {
	var b strings.Builder
	fmt.Fprintf(&b, "---\nid: %s\nseverity: %s\npublished: %s\ntechs: [%s]\n---\n", v.ID, v.Severity,
		v.Published.UTC().Format("2006-01-02"), strings.Join(v.Techs, ", "))
	fmt.Fprintf(&b, "# %s — %s\n\n", v.ID, md(v.Title))
	b.WriteString("_Generated by cvewatch. Change status with the CLI, not by hand._\n\n")
	if len(v.Aliases) > 0 {
		fmt.Fprintf(&b, "**Also reported as:** %s\n\n", strings.Join(v.Aliases, ", "))
	}
	if v.CVSS > 0 {
		fmt.Fprintf(&b, "**CVSS:** %.1f\n\n", v.CVSS)
	}

	b.WriteString("## Description\n\n")
	if v.Summary != "" {
		fmt.Fprintf(&b, "%s\n\n", md(query.Clip(v.Summary, 600)))
	} else {
		b.WriteString("_The feed gave no description. Read the original below._\n\n")
	}
	if len(v.Refs) > 0 {
		fmt.Fprintf(&b, "**Original:** %s\n\n", md(v.Refs[0].URL))
	}
	if len(v.Refs) > 1 {
		b.WriteString("**More reports:**\n")
		for _, r := range v.Refs[1:] {
			fmt.Fprintf(&b, "- %s (%s)\n", md(r.URL), md(r.Source))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Status\n\n| Project | Env | Status | Matched | Note |\n|---|---|---|---|---|\n")
	for _, f := range fs {
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", cell(f.Project), f.Env, f.Status,
			cell(strings.Join(f.Matched, ", ")), cell(f.Note))
	}

	b.WriteString("\n## Plan\n")
	for _, p := range byProject(fs) {
		b.WriteString(plan(v, p))
	}
	return b.String()
}

// md neutralizes markup in text that came from outside, so a hostile feed
// entry cannot inject HTML or fake structure into a report.
func md(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}

// cell makes text safe inside one markdown table cell.
func cell(s string) string { return strings.ReplaceAll(md(s), "|", "\\|") }

func plan(v *model.Vulnerability, fs []model.Finding) string {
	var b strings.Builder
	project := fs[0].Project
	fmt.Fprintf(&b, "\n### %s\n\n", project)
	fmt.Fprintf(&b, "1. Read the sources and confirm the deployed version is affected (matched: %s).\n",
		md(strings.Join(fs[0].Matched, ", ")))
	if len(fs) == 1 {
		fmt.Fprintf(&b, "2. Apply the fix or mitigation in %s (its only environment) and verify.\n", fs[0].Env)
	} else {
		b.WriteString("2. Fix environments in order; promote only after the previous one is verified.\n")
	}
	for _, f := range fs {
		fmt.Fprintf(&b, "   - %s %s — `cvewatch fix %s --project %s --env %s`\n", box(f.Status), f.Env, v.ID, project, f.Env)
	}
	b.WriteString("3. If no fix exists yet, mitigate (disable the feature, block at WAF/proxy) and use `cvewatch ignore` only when it does not apply.\n")
	return b.String()
}

func box(s model.Status) string {
	switch s {
	case model.StatusFixed:
		return "[x]"
	case model.StatusIgnored:
		return "[-]"
	}
	return "[ ]"
}

// byProject splits sorted findings into one slice per project.
func byProject(fs []model.Finding) [][]model.Finding {
	var out [][]model.Finding
	for _, f := range fs {
		if n := len(out); n > 0 && out[n-1][0].Project == f.Project {
			out[n-1] = append(out[n-1], f)
		} else {
			out = append(out, []model.Finding{f})
		}
	}
	return out
}

// Digest renders open issues as returned by query.Open: grouped by severity,
// one entry per issue. fresh marks ids that arrived in the latest cycle.
// It runs after every cycle, so unresolved issues keep showing up until
// someone marks them fixed.
func Digest(issues []query.Issue, fresh map[string]bool) string {
	if len(issues) == 0 {
		return "No open findings.\n"
	}
	counts := map[model.Severity]int{}
	for _, is := range issues {
		counts[is.Severity]++
	}

	var b strings.Builder
	fmt.Fprintf(&b, "Open findings: %d\n", len(issues))
	var current model.Severity
	for i, is := range issues {
		if i == 0 || is.Severity != current {
			current = is.Severity
			fmt.Fprintf(&b, "\n%s (%d)\n", label(current), counts[current])
		}
		mark := "    "
		if fresh[is.ID] {
			mark = "NEW "
		}
		fmt.Fprintf(&b, "  %s%-18s %s\n", mark, is.ID, where(is))
		fmt.Fprintf(&b, "      %s\n", query.Clip(is.Untrusted.Title, 100))
		if len(is.Refs) > 0 {
			fmt.Fprintf(&b, "      %s\n", is.Refs[0].URL)
		}
	}
	return b.String()
}

func label(s model.Severity) string {
	if s == model.SevUnknown {
		return "UNRATED"
	}
	return strings.ToUpper(string(s))
}

// where renders "shop: dev,prod; middleware: prod" plus a count of related reports.
func where(is query.Issue) string {
	var projects []string
	envs := map[string][]string{}
	for _, t := range is.Targets {
		if _, seen := envs[t.Project]; !seen {
			projects = append(projects, t.Project)
		}
		envs[t.Project] = append(envs[t.Project], string(t.Env))
	}
	parts := make([]string, len(projects))
	for i, p := range projects {
		parts[i] = p + ": " + strings.Join(envs[p], ",")
	}
	out := strings.Join(parts, "; ")
	if n := len(is.Aliases) + len(is.Refs) - 1; n > 0 {
		out += fmt.Sprintf("  (+%d related)", n)
	}
	return out
}
