// Package report writes the human-facing views: one markdown file per
// vulnerability (alerts/YYYY/yyyy-mm-dd-tech-slug.md) and a digest of open work.
// Files are generated from the ledger, which stays the source of truth.
package report

import (
	"fmt"
	"path/filepath"
	"strings"
	"time"

	"github.com/b070nd/cvewatch/app/src/evidence"
	"github.com/b070nd/cvewatch/app/src/host"
	"github.com/b070nd/cvewatch/app/src/model"
	"github.com/b070nd/cvewatch/app/src/query"
)

// Path is stable for a vulnerability: it only uses the first-seen date and
// the techs frozen at evaluation, so later config edits never move files.
func Path(alertsDir string, v *model.Vulnerability) string {
	tech := "deps"
	if len(v.Techs) > 0 {
		tech = v.Techs[0]
	}
	day := v.FirstSeen.UTC().Format("2006-01-02")
	name := fmt.Sprintf("%s-%s-%s.md", day, slug(tech), slug(v.ID))
	return filepath.Join(alertsDir, v.FirstSeen.UTC().Format("2006"), name)
}

func slug(s string) string {
	s = strings.ToLower(s)
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' {
			return r
		}
		return '-'
	}, s)
}

// Write renders and stores the report, returning its path.
func Write(alertsDir string, v *model.Vulnerability, fs []model.Finding, now time.Time) (string, error) {
	p := Path(alertsDir, v)
	return p, host.WriteFileAtomic(p, []byte(Render(v, fs, now)))
}

// Render builds the markdown for a vulnerability and its findings. The
// history is the one the ledger keeps, since no audit log is at hand here.
func Render(v *model.Vulnerability, fs []model.Finding, now time.Time) string {
	d := query.DetailOf(v, fs, now)
	d.History = evidence.Build(v, fs, nil, nil, false, now).History()
	return RenderDetail(d)
}

// RenderDetail builds the markdown: description, fix evidence, the articles
// in chronological order, status table, history and a rollout plan per
// project.
func RenderDetail(d query.Detail) string {
	is := d.Issue
	var b strings.Builder
	fmt.Fprintf(&b, "---\nid: %s\nseverity: %s\npublished: %s\ntechs: [%s]\n---\n", is.ID, is.Severity,
		is.Published.UTC().Format("2006-01-02"), strings.Join(is.Techs, ", "))
	fmt.Fprintf(&b, "# %s — %s\n\n", is.ID, md(is.Untrusted.Title))
	b.WriteString("_Generated by cvewatch. Change status with the CLI, not by hand._\n\n")
	if len(is.Aliases) > 0 {
		fmt.Fprintf(&b, "**Also reported as:** %s\n\n", strings.Join(is.Aliases, ", "))
	}
	fmt.Fprintf(&b, "**Published:** %s", is.Published.UTC().Format("2006-01-02"))
	if is.Age != "" {
		fmt.Fprintf(&b, " (%s ago)", is.Age)
	}
	fmt.Fprintf(&b, " · **Articles found:** %d", is.ArticleCount)
	if is.CVSS > 0 {
		fmt.Fprintf(&b, " · **CVSS:** %s", is.CVSSText())
	}
	b.WriteString("\n\n")
	if o := is.CVSSOrigin(); o != "" {
		fmt.Fprintf(&b, "**CVSS detail:** %s\n\n", o)
	}
	if k := is.KEV; k != nil {
		fmt.Fprintf(&b, "**KEV:** on CISA's Known Exploited Vulnerabilities list since %s", k.DateAdded.UTC().Format("2006-01-02"))
		if !k.DueDate.IsZero() {
			fmt.Fprintf(&b, ", CISA remediation due %s", k.DueDate.UTC().Format("2006-01-02"))
		}
		if k.Ransomware {
			b.WriteString(", known ransomware use")
		}
		if is.Untrusted.KEVAction != "" {
			fmt.Fprintf(&b, ". Required action: %s", md(is.Untrusted.KEVAction))
		}
		b.WriteString("\n\n")
	}
	if e := is.EPSS; e != nil {
		fmt.Fprintf(&b, "**EPSS:** %.0f%% chance of exploitation in the next 30 days (percentile %.0f)\n\n", e.Score*100, e.Percentile*100)
	}
	if len(d.Why) > 0 {
		fmt.Fprintf(&b, "**Why it ranks where it does:** %s\n\n", strings.Join(d.Why, "; "))
	}
	b.WriteString("## Description\n\n")
	if is.Untrusted.Description != "" {
		fmt.Fprintf(&b, "%s\n\n", md(is.Untrusted.Description))
	} else {
		b.WriteString("_The feed gave no description. Read the sources below._\n\n")
	}

	b.WriteString("## Fix\n\n")
	if len(is.Untrusted.Fixes) == 0 {
		b.WriteString("No official fix, patch or mitigation was named by the feeds yet. Check the vendor.\n\n")
	}
	for _, f := range is.Untrusted.Fixes {
		official := ""
		if f.Official {
			official = ", official"
		}
		detail := ""
		if f.Detail != "" {
			detail = " " + md(f.Detail)
		}
		fmt.Fprintf(&b, "- **%s**%s (%s%s) %s\n", f.Kind, detail, md(f.Source), official, md(f.URL))
	}
	if len(is.Untrusted.Fixes) > 0 {
		b.WriteString("\n")
	}

	if len(d.Affected) > 0 {
		b.WriteString("## Affected\n\n")
		for _, a := range d.Affected {
			fmt.Fprintf(&b, "- %s %s: %s", md(a.Ecosystem), md(a.Name), code(query.RangeText(a.Ranges)))
			if a.Fixed != "" {
				fmt.Fprintf(&b, " (first fixed %s)", md(a.Fixed))
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## Articles, oldest first\n\n")
	if len(is.Untrusted.Articles) == 0 {
		b.WriteString("None yet.\n")
	}
	for i, a := range is.Untrusted.Articles {
		day := "undated"
		if !a.Published.IsZero() {
			day = a.Published.UTC().Format("2006-01-02")
		}
		fmt.Fprintf(&b, "%d. %s · %s · %s\n   %s\n", i+1, day, md(a.Source), md(a.Title), md(a.URL))
	}
	var advisories []query.Link
	for _, l := range d.Links {
		if l.Kind == query.LinkAdvisory {
			advisories = append(advisories, l)
		}
	}
	if len(advisories) > 0 {
		b.WriteString("\n**Advisories:**\n")
		for _, l := range advisories {
			fmt.Fprintf(&b, "- %s (%s)\n", md(l.URL), md(l.Source))
		}
	}

	b.WriteString("\n## Status\n\n| Project | Env | Status | Version | Owner | Due | Ticket | Matched | Note |\n|---|---|---|---|---|---|---|---|---|\n")
	for _, t := range is.Targets {
		due := ""
		if !t.Due.IsZero() {
			due = t.Due.UTC().Format("2006-01-02")
			if t.Overdue {
				due += " (overdue)"
			}
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", cell(t.Project), t.Env, t.Status, applies(t.Applies),
			cell(t.Owner), due, cell(t.Ticket), cell(strings.Join(t.Matched, ", ")), cell(t.Note))
	}
	var installed, attached []string
	for _, t := range d.Targets {
		var labels []string
		for _, i := range t.Installed {
			labels = append(labels, md(i.Label())+" ("+md(i.Via)+")")
		}
		if len(labels) > 0 {
			installed = append(installed, fmt.Sprintf("- %s/%s: %s", cell(t.Project), t.Env, strings.Join(labels, ", ")))
		}
		for _, e := range t.Evidence {
			attached = append(attached, fmt.Sprintf("- %s/%s, %s by %s: %s %s", cell(t.Project), t.Env,
				e.Time.UTC().Format("2006-01-02"), cell(e.Actor), md(e.Note), md(e.URL)))
		}
	}
	if len(installed) > 0 {
		b.WriteString("\n**Installed:**\n" + strings.Join(installed, "\n") + "\n")
	}
	if len(attached) > 0 {
		b.WriteString("\n**Evidence:**\n" + strings.Join(attached, "\n") + "\n")
	}

	if len(d.History) > 0 {
		b.WriteString("\n## History\n\n")
		for _, h := range d.History {
			line := fmt.Sprintf("- %s **%s** %s", h.Time.UTC().Format("2006-01-02 15:04"), md(h.Kind), md(h.Detail))
			if h.Actor != "" {
				line += " (by " + md(query.ActorLabel(h.Actor)) + ")"
			}
			if h.URL != "" {
				line += " " + md(h.URL)
			}
			b.WriteString(line + "\n")
		}
	}

	b.WriteString("\n## Plan\n")
	for _, p := range byProject(is.Targets) {
		b.WriteString(plan(is.ID, p))
	}
	return b.String()
}

func applies(a model.Applicability) string {
	switch a {
	case model.AppAffected:
		return "affected"
	case model.AppNotAffected:
		return "not affected"
	}
	return "unchecked"
}

// md neutralizes markup in text that came from outside, so a hostile feed
// entry cannot inject HTML or fake structure into a report.
func md(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}

// code puts feed text in an inline code span, where markup is inert.
func code(s string) string {
	return "`" + strings.ReplaceAll(strings.Join(strings.Fields(s), " "), "`", "'") + "`"
}

// cell makes text safe inside one markdown table cell.
func cell(s string) string { return strings.ReplaceAll(md(s), "|", "\\|") }

func plan(id string, ts []query.Target) string {
	var b strings.Builder
	project := ts[0].Project
	fmt.Fprintf(&b, "\n### %s\n\n", project)
	fmt.Fprintf(&b, "1. %s (matched: %s).\n", check(ts[0]), md(strings.Join(ts[0].Matched, ", ")))
	for _, r := range ts[0].Reasons {
		fmt.Fprintf(&b, "   - %s\n", md(r))
	}
	if len(ts) == 1 {
		fmt.Fprintf(&b, "2. Apply the fix or mitigation in %s (its only environment) and verify.\n", ts[0].Env)
	} else {
		b.WriteString("2. Fix environments in order; promote only after the previous one is verified.\n")
	}
	for _, t := range ts {
		fmt.Fprintf(&b, "   - %s %s — `cvewatch fix %s --project %s --env %s`\n", box(t.Status), t.Env, id, project, t.Env)
	}
	b.WriteString("3. If no fix exists yet, mitigate (disable the feature, block at WAF/proxy) and use `cvewatch ignore` only when it does not apply.\n")
	return b.String()
}

// check words step one by what the version check could establish.
func check(t query.Target) string {
	switch t.Applies {
	case model.AppAffected:
		return "The installed version is inside the affected range; confirm and plan the upgrade"
	case model.AppNotAffected:
		return "The installed version is outside the affected range; confirm, then close with `ignore`"
	}
	return "Read the sources and confirm the deployed version is affected"
}

func box(s model.Status) string {
	switch s {
	case model.StatusFixed:
		return "[x]"
	case model.StatusIgnored:
		return "[-]"
	}
	return "[ ]"
}

// byProject splits sorted targets into one slice per project.
func byProject(ts []query.Target) [][]query.Target {
	var out [][]query.Target
	for _, t := range ts {
		if n := len(out); n > 0 && out[n-1][0].Project == t.Project {
			out[n-1] = append(out[n-1], t)
		} else {
			out = append(out, []query.Target{t})
		}
	}
	return out
}

// Digest renders open issues as returned by query.Open: grouped by severity,
// one entry per issue. fresh marks ids that arrived in the latest cycle.
// It runs after every cycle, so unresolved issues keep showing up until
// someone marks them fixed.
func Digest(issues []query.Issue, fresh map[string]bool) string {
	if len(issues) == 0 {
		return "No open findings.\n"
	}
	return list("Open findings", issues, fresh, where)
}

func Matches(issues []query.Issue) string {
	return list("Matches", issues, nil, statuses)
}

func list(heading string, issues []query.Issue, fresh map[string]bool, targets func(query.Issue) string) string {
	counts := map[model.Severity]int{}
	for _, is := range issues {
		counts[is.Severity]++
	}

	var b strings.Builder
	fmt.Fprintf(&b, "%s: %d\n", heading, len(issues))
	var current model.Severity
	for i, is := range issues {
		if i == 0 || is.Severity != current {
			current = is.Severity
			fmt.Fprintf(&b, "\n%s (%d)\n", label(current), counts[current])
		}
		mark := "    "
		if fresh[is.ID] {
			mark = "NEW "
		}
		fmt.Fprintf(&b, "  %s%-18s %s\n", mark, is.ID, targets(is))
		fmt.Fprintf(&b, "      %s\n", query.Clip(is.Untrusted.Title, 100))
		fmt.Fprintf(&b, "      %s\n", facts(is))
		if len(is.Untrusted.Articles) > 0 {
			fmt.Fprintf(&b, "      %s\n", is.Untrusted.Articles[0].URL)
		}
	}
	return b.String()
}

// facts is the one-line summary: age, article count and fix status.
func facts(is query.Issue) string {
	parts := []string{}
	if is.Age != "" {
		parts = append(parts, "published "+is.Age+" ago")
	}
	parts = append(parts, plural(is.ArticleCount, "article"))
	if k := is.KEV; k != nil {
		kev := "KEV"
		if !k.DueDate.IsZero() {
			kev += ", CISA due " + k.DueDate.Format("2006-01-02")
		}
		parts = append(parts, kev)
	}
	if is.EPSS != nil {
		parts = append(parts, fmt.Sprintf("EPSS %.0f%%", is.EPSS.Score*100))
	}
	for _, t := range is.Targets {
		if t.Overdue {
			parts = append(parts, "OVERDUE")
			break
		}
	}
	switch {
	case is.Fix.Official:
		parts = append(parts, "official fix: "+fixWhat(is))
	case is.Fix.Available:
		parts = append(parts, "fix reference: "+fixWhat(is))
	default:
		parts = append(parts, "no fix known")
	}
	return strings.Join(parts, " · ")
}

// fixWhat names the patched version when a feed gave one, else the kind of remedy.
func fixWhat(is query.Issue) string {
	for _, f := range is.Untrusted.Fixes {
		if f.Kind == model.FixVersion && f.Detail != "" {
			return f.Detail
		}
	}
	return string(is.Untrusted.Fixes[0].Kind)
}

func plural(n int, word string) string {
	if n == 1 {
		return "1 " + word
	}
	return fmt.Sprintf("%d %ss", n, word)
}

func label(s model.Severity) string {
	if s == model.SevUnknown {
		return "UNRATED"
	}
	return strings.ToUpper(string(s))
}

// where renders "shop: dev,prod; middleware: prod", the version verdict and a
// count of related ids.
func where(is query.Issue) string {
	var projects []string
	envs := map[string][]string{}
	for _, t := range is.Targets {
		if _, seen := envs[t.Project]; !seen {
			projects = append(projects, t.Project)
		}
		envs[t.Project] = append(envs[t.Project], string(t.Env))
	}
	parts := make([]string, len(projects))
	for i, p := range projects {
		parts[i] = p + ": " + strings.Join(envs[p], ",")
	}
	out := strings.Join(parts, "; ") + "  [" + applies(is.Applies) + "]"
	if n := len(is.Aliases); n > 0 {
		out += fmt.Sprintf("  (+%d ids)", n)
	}
	return out
}

func statuses(is query.Issue) string {
	parts := make([]string, len(is.Targets))
	for i, t := range is.Targets {
		parts[i] = fmt.Sprintf("%s/%s %s", t.Project, t.Env, t.Status)
	}
	out := strings.Join(parts, ", ") + "  [" + applies(is.Applies) + "]"
	if n := len(is.Aliases); n > 0 {
		out += fmt.Sprintf("  (+%d ids)", n)
	}
	return out
}
