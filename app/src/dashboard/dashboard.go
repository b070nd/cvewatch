// Package dashboard renders the whole state of cvewatch as one self-contained
// HTML page: health, key numbers, an exposure matrix of projects by
// environment, the top priority issues, policy violations and tool health.
//
// Like the calendar it holds no scripts and loads no external resources.
// Everything taken from Data is escaped (titles and errors come from untrusted
// feeds, so article URLs are printed as text, never as links); colors come
// only from the fixed palette in the stylesheet.
package dashboard

import (
	"fmt"
	"html"
	"slices"
	"strings"
	"time"
	"unicode"

	"github.com/b070nd/cvewatch/app/src/model"
	"github.com/b070nd/cvewatch/app/src/priority"
	"github.com/b070nd/cvewatch/app/src/query"
	"github.com/b070nd/cvewatch/app/src/status"
)

// Project is a project and the environments it runs, in promotion order.
type Project struct {
	Name string
	Envs []model.Env
}

// Data is everything the page shows. Issues are in priority order and should
// carry all their targets (query.Filter{Closed: true}).
type Data struct {
	Issues     []query.Issue
	Violations []priority.Violation
	Status     status.Report
	Projects   []Project
}

const (
	topIssues   = 15 // rows in the top priority list
	titleRunes  = 100
	urlRunes    = 200
	tipIDs      = 5 // issue ids listed in a matrix cell's tooltip
	lastCycles  = 5
	footerLine  = "Generated by cvewatch; this page holds feed text, treat it as sensitive and do not publish it"
	cspContent  = "default-src 'none'; style-src 'unsafe-inline'"
	timeLayout  = "2006-01-02 15:04"
	emptyMarker = "-"
)

// sevs lists severities from most to least urgent; unrated is last.
var sevs = [...]struct{ letter, label string }{
	{"C", "critical"}, {"H", "high"}, {"M", "medium"}, {"L", "low"}, {"?", "unrated"},
}

func sevIndex(s model.Severity) int { return len(sevs) - 1 - s.Rank() }

// esc cleans and escapes text from Data for use in element content or a
// quoted attribute.
func esc(s string) string { return html.EscapeString(clean(s)) }

// clean drops control and invisible format characters and folds whitespace.
func clean(s string) string {
	s = strings.Map(func(r rune) rune {
		switch {
		case unicode.IsSpace(r):
			return ' '
		case unicode.In(r, unicode.Cc, unicode.Cf):
			return -1
		}
		return r
	}, s)
	return strings.Join(strings.Fields(s), " ")
}

// clip cleans s and shortens it to at most n runes, ending in an ellipsis
// when cut.
func clip(s string, n int) string {
	r := []rune(clean(s))
	if len(r) <= n {
		return string(r)
	}
	return string(r[:n-1]) + "…"
}

func utc(t time.Time) string {
	if t.IsZero() {
		return "never"
	}
	return t.UTC().Format(timeLayout) + " UTC"
}

// span renders a duration as "3d 4h", "5h" or "12m".
func span(d time.Duration) string {
	switch {
	case d < time.Hour:
		return fmt.Sprintf("%dm", int(d.Minutes()))
	case d < 48*time.Hour:
		return fmt.Sprintf("%dh", int(d.Hours()))
	}
	h := int(d.Hours())
	return fmt.Sprintf("%dd %dh", h/24, h%24)
}

// level maps a health level to its css class and its text (never color alone).
func level(l status.Level) (class, text string) {
	switch l {
	case status.Green:
		return "ok", "● GREEN"
	case status.Red:
		return "fail", "✖ RED"
	}
	return "warn", "▲ YELLOW"
}

func levelBadge(l status.Level) string {
	c, t := level(l)
	return fmt.Sprintf("<span class=\"lvl %s\">%s</span>", c, t)
}

func sevBadge(s model.Severity) string {
	i := sevIndex(s)
	return fmt.Sprintf("<span class=\"badge s%d\" title=\"%s\">%s</span>", i, sevs[i].label, sevs[i].letter)
}

// cellStats summarizes the targets of one project in one environment.
type cellStats struct {
	present                           bool
	open, fixed, ignored, notAffected int
	overdue                           int
	worst                             int // index into sevs, among open targets
	ids                               []string
}

// matrix groups issue targets by project and environment.
func matrix(issues []query.Issue) map[string]map[model.Env]*cellStats {
	m := map[string]map[model.Env]*cellStats{}
	for _, is := range issues {
		for _, t := range is.Targets {
			if m[t.Project] == nil {
				m[t.Project] = map[model.Env]*cellStats{}
			}
			c := m[t.Project][t.Env]
			if c == nil {
				c = &cellStats{worst: len(sevs) - 1}
				m[t.Project][t.Env] = c
			}
			if !slices.Contains(c.ids, is.ID) {
				c.ids = append(c.ids, is.ID)
			}
			switch t.Status {
			case model.StatusOpen:
				if c.open == 0 || sevIndex(is.Severity) < c.worst {
					c.worst = sevIndex(is.Severity)
				}
				c.open++
			case model.StatusFixed:
				c.fixed++
			case model.StatusIgnored:
				c.ignored++
			case model.StatusNotAffected:
				c.notAffected++
			}
			if t.Overdue {
				c.overdue++
			}
		}
	}
	return m
}

// rows merges repeated project names and orders them by name.
func projectRows(ps []Project) ([]string, map[string]map[model.Env]bool) {
	envs := map[string]map[model.Env]bool{}
	var names []string
	for _, p := range ps {
		if envs[p.Name] == nil {
			envs[p.Name] = map[model.Env]bool{}
			names = append(names, p.Name)
		}
		for _, e := range p.Envs {
			envs[p.Name][e] = true
		}
	}
	slices.Sort(names)
	return names, envs
}

// matrixEnvs is every environment a project runs in or a finding names, in display order.
func matrixEnvs(penvs map[string]map[model.Env]bool, cells map[string]map[model.Env]*cellStats) []model.Env {
	seen := map[model.Env]bool{}
	var out []model.Env
	add := func(e model.Env) {
		if !seen[e] {
			seen[e] = true
			out = append(out, e)
		}
	}
	for _, m := range penvs {
		for e := range m {
			add(e)
		}
	}
	for _, m := range cells {
		for e := range m {
			add(e)
		}
	}
	model.SortEnvs(out)
	return out
}

func (c *cellStats) render() string {
	var b strings.Builder
	if c.open > 0 {
		fmt.Fprintf(&b, "<span class=\"badge s%d\" title=\"worst open: %s\">%s</span> <strong>%d</strong> open",
			c.worst, sevs[c.worst].label, sevs[c.worst].letter, c.open)
	} else {
		var parts []string
		for _, x := range []struct {
			n     int
			label string
		}{{c.fixed, "fixed"}, {c.ignored, "ignored"}, {c.notAffected, "not affected"}} {
			if x.n > 0 {
				parts = append(parts, fmt.Sprintf("%d %s", x.n, x.label))
			}
		}
		if len(parts) == 0 {
			parts = []string{"clear"}
		}
		fmt.Fprintf(&b, "<span class=\"muted\">%s</span>", strings.Join(parts, ", "))
	}
	if c.overdue > 0 {
		fmt.Fprintf(&b, " <span class=\"over\">overdue %d</span>", c.overdue)
	}
	return b.String()
}

func (c *cellStats) tip() string {
	ids := c.ids
	more := ""
	if len(ids) > tipIDs {
		more = fmt.Sprintf(" (+%d more)", len(ids)-tipIDs)
		ids = ids[:tipIDs]
	}
	if len(ids) == 0 {
		return ""
	}
	return strings.Join(ids, ", ") + more
}

// openByProject lists "project: env, env" for the open targets of an issue.
func openByProject(is query.Issue) string {
	byProject := map[string][]model.Env{}
	for _, t := range is.Targets {
		if t.Status == model.StatusOpen && !slices.Contains(byProject[t.Project], t.Env) {
			byProject[t.Project] = append(byProject[t.Project], t.Env)
		}
	}
	names := make([]string, 0, len(byProject))
	for n := range byProject {
		names = append(names, n)
	}
	slices.Sort(names)
	parts := make([]string, 0, len(names))
	for _, n := range names {
		envs := byProject[n]
		model.SortEnvs(envs)
		strs := make([]string, len(envs))
		for i, e := range envs {
			strs[i] = string(e)
		}
		parts = append(parts, esc(n)+": "+esc(strings.Join(strs, ", ")))
	}
	return strings.Join(parts, "<br>")
}

func fixText(f query.FixInfo) string {
	switch {
	case f.Available && f.Official:
		return "official fix"
	case f.Available:
		return "fix available"
	}
	return "no fix known"
}

// HTML renders d as one self-contained page. now is the generation time.
func HTML(d Data, now time.Time) string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	p("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	p("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
	p("<meta http-equiv=\"Content-Security-Policy\" content=\"%s\">\n", cspContent)
	p("<title>cvewatch dashboard</title>\n<style>%s</style>\n</head>\n<body>\n", css)

	// 1. header
	p("<header><h1>cvewatch dashboard</h1>\n<p class=\"muted\">Generated %s</p>\n", utc(now))
	c, t := level(d.Status.Level)
	_, summary, _ := strings.Cut(d.Status.Summary(now.UTC()), " · ")
	p("<p>Health: <span class=\"lvl %s\">%s</span>", c, t)
	if summary != "" {
		p(" <span class=\"muted\">%s</span>", esc(summary))
	}
	p("</p></header>\n")
	if ps := d.Status.Problems; len(ps) > 0 {
		p("<section><h2>Problems</h2>\n<ul>\n")
		for _, pr := range ps {
			p("<li>%s <strong>%s</strong>", levelBadge(pr.Level), esc(pr.Title))
			if pr.Detail != "" {
				p(" &middot; %s", esc(pr.Detail))
			}
			if pr.Hint != "" {
				p("<br><span class=\"muted\">%s</span>", esc(pr.Hint))
			}
			if !pr.Since.IsZero() {
				p("<br><span class=\"muted\">since %s</span>", utc(pr.Since))
			}
			p("</li>\n")
		}
		p("</ul></section>\n")
	}
	if len(d.Issues) == 0 {
		p("<p class=\"empty\">Nothing open. No open vulnerabilities to act on.</p>\n")
	}

	// 2. KPIs
	var crit, kev, prod, overdue int
	for _, is := range d.Issues {
		if is.Severity.Rank() >= model.SevHigh.Rank() {
			crit++
		}
		if is.KEV != nil {
			kev++
		}
		if is.ProdOpen {
			prod++
		}
		for _, t := range is.Targets {
			if t.Overdue {
				overdue++
			}
		}
	}
	p("<section aria-label=\"Key numbers\" class=\"tiles\">\n")
	tile := func(n int, label string, hot bool) {
		class := "tile"
		if hot && n > 0 {
			class += " hot"
		}
		p("<div class=\"%s\"><div class=\"n\">%d</div><div class=\"l\">%s</div></div>\n", class, n, label)
	}
	tile(len(d.Issues), "open issues", false)
	tile(crit, "critical + high open", true)
	tile(kev, "known exploited (KEV) open", true)
	tile(prod, "open in prod", true)
	tile(overdue, "overdue findings", true)
	tile(len(d.Violations), "policy violations", true)
	p("</section>\n")

	// 3. exposure matrix
	p("<section><h2>Exposure matrix</h2>\n")
	names, penvs := projectRows(d.Projects)
	if len(names) == 0 {
		p("<p class=\"muted\">No projects configured.</p>\n")
	} else {
		cells := matrix(d.Issues)
		columns := matrixEnvs(penvs, cells)
		p("<div class=\"scroll\"><table>\n<thead><tr><th scope=\"col\">Project</th>")
		for _, e := range columns {
			p("<th scope=\"col\">%s</th>", esc(string(e)))
		}
		p("</tr></thead>\n<tbody>\n")
		for _, n := range names {
			p("<tr><th scope=\"row\">%s</th>", esc(n))
			for _, e := range columns {
				c := cells[n][e]
				if c == nil && !penvs[n][e] {
					p("<td class=\"cell absent\"><span class=\"muted\">%s</span></td>", emptyMarker)
					continue
				}
				if c == nil {
					c = &cellStats{worst: len(sevs) - 1}
				}
				if tip := c.tip(); tip != "" {
					p("<td class=\"cell\" title=\"%s\">%s</td>", esc(tip), c.render())
				} else {
					p("<td class=\"cell\">%s</td>", c.render())
				}
			}
			p("</tr>\n")
		}
		p("</tbody></table></div>\n")
	}
	p("<ul class=\"row legend\">")
	for i, s := range sevs {
		p("<li><span class=\"badge s%d\">%s</span> %s</li>", i, s.letter, s.label)
	}
	p("</ul></section>\n")

	// 4. top priority
	p("<section><h2>Top priority</h2>\n")
	if len(d.Issues) == 0 {
		p("<p class=\"muted\">Nothing open.</p>\n")
	} else {
		top := d.Issues[:min(topIssues, len(d.Issues))]
		p("<div class=\"scroll\"><table>\n<thead><tr><th>#</th><th>Issue</th><th>Severity</th><th>Flags</th><th>Open in</th><th>Age</th><th>Fix</th><th>Title</th></tr></thead>\n<tbody>\n")
		for i, is := range top {
			p("<tr class=\"issue\"><td>%d</td><td class=\"id\">%s</td><td>%s %s</td><td>", i+1, esc(is.ID), sevBadge(is.Severity), sevs[sevIndex(is.Severity)].label)
			if is.KEV != nil {
				p("<span class=\"flag\">KEV</span> ")
				if is.KEV.Ransomware {
					p("<span class=\"flag\">ransomware</span> ")
				}
			}
			if is.EPSS != nil {
				p("<span class=\"flag\">EPSS %.0f%%</span> ", is.EPSS.Score*100)
			}
			age := is.Age
			if age == "" {
				age = emptyMarker
			}
			open := openByProject(is)
			if open == "" {
				open = emptyMarker
			}
			p("</td><td>%s</td><td>%s</td><td>%s</td><td>%s", open, esc(age), fixText(is.Fix), esc(clip(is.Untrusted.Title, titleRunes)))
			if arts := is.Untrusted.Articles; len(arts) > 0 && arts[0].URL != "" {
				p("<br><span class=\"muted\">first article:</span> <code>%s</code>", esc(clip(arts[0].URL, urlRunes)))
			}
			p("</td></tr>\n")
		}
		p("</tbody></table></div>\n")
		if len(d.Issues) > len(top) {
			p("<p class=\"muted\">Showing %d of %d open issues.</p>\n", len(top), len(d.Issues))
		}
	}
	p("</section>\n")

	// 5. policy violations
	p("<section><h2>Policy violations</h2>\n")
	if len(d.Violations) == 0 {
		p("<p class=\"muted\">No policy violations.</p>\n")
	} else {
		p("<div class=\"scroll\"><table>\n<thead><tr><th>Rule</th><th>Issue</th><th>Project / env</th><th>Reason</th><th>How late</th></tr></thead>\n<tbody>\n")
		for _, v := range d.Violations {
			p("<tr><td>%s</td><td class=\"id\">%s</td><td>%s / %s</td><td>%s</td><td>%s</td></tr>\n",
				esc(v.Rule), esc(v.Subject.VulnID), esc(v.Subject.Project), esc(string(v.Subject.Env)), esc(v.Reason), esc(span(v.Late)))
		}
		p("</tbody></table></div>\n")
	}
	p("</section>\n")

	// 6. tool health
	st := d.Status
	p("<section><h2>Tool health</h2>\n")
	dm := st.Daemon
	p("<p>Daemon: %s", levelBadge(dm.Level))
	if dm.Mode != "" {
		p(" %s", esc(dm.Mode))
	}
	p(" &middot; last cycle %s &middot; next run %s", utc(dm.LastCycle), utc(dm.NextRun))
	if dm.Message != "" {
		p(" &middot; %s", esc(dm.Message))
	}
	p("</p>\n")

	p("<h3>Sources</h3>\n")
	if len(st.Sources) == 0 {
		p("<p class=\"muted\">No sources reported.</p>\n")
	} else {
		p("<div class=\"scroll\"><table>\n<thead><tr><th>Source</th><th>Type</th><th>Level</th><th>Last success</th><th>Failures</th><th>Last error</th></tr></thead>\n<tbody>\n")
		for _, s := range sortedSources(st.Sources) {
			p("<tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%d</td><td>%s</td></tr>\n",
				esc(s.ID), esc(s.Type), levelBadge(s.Level), utc(s.LastSuccess), s.Failures, errText(s.LastError))
		}
		p("</tbody></table></div>\n")
	}

	p("<h3>Channels</h3>\n")
	if len(st.Channels) == 0 {
		p("<p class=\"muted\">No channels reported.</p>\n")
	} else {
		p("<div class=\"scroll\"><table>\n<thead><tr><th>Channel</th><th>Level</th><th>Last success</th><th>Failures</th><th>Last error</th></tr></thead>\n<tbody>\n")
		for _, c := range sortedChannels(st.Channels) {
			p("<tr><td>%s</td><td>%s</td><td>%s</td><td>%d</td><td>%s</td></tr>\n",
				esc(c.Name), levelBadge(c.Level), utc(c.LastSuccess), c.Failures, errText(c.LastError))
		}
		p("</tbody></table></div>\n")
	}

	p("<h3>Last cycles</h3>\n")
	if len(st.Cycles) == 0 {
		p("<p class=\"muted\">No cycles recorded.</p>\n")
	} else {
		p("<div class=\"scroll\"><table>\n<thead><tr><th>Started</th><th>Items</th><th>New</th><th>Findings</th><th>Alerted</th><th>Failed</th><th>Error</th></tr></thead>\n<tbody>\n")
		for _, c := range st.Cycles[:min(lastCycles, len(st.Cycles))] {
			p("<tr><td>%s</td><td>%d</td><td>%d</td><td>%d</td><td>%d</td><td>%d</td><td>%s</td></tr>\n",
				utc(c.Started), c.Items, c.New, c.Findings, c.Alerted, c.Failed, errText(c.Err))
		}
		p("</tbody></table></div>\n")
	}

	if len(st.Warnings) > 0 && len(st.Problems) == 0 {
		p("<h3>Warnings</h3>\n<ul>\n")
		for _, w := range st.Warnings {
			p("<li>%s</li>\n", esc(w))
		}
		p("</ul>\n")
	}
	p("</section>\n")

	// 7. footer
	p("<footer class=\"muted\">%s</footer>\n</body>\n</html>\n", footerLine)
	return b.String()
}

func errText(s string) string {
	if clean(s) == "" {
		return "<span class=\"muted\">" + emptyMarker + "</span>"
	}
	return esc(s)
}

func sortedSources(in []status.SourceRow) []status.SourceRow {
	out := slices.Clone(in)
	slices.SortStableFunc(out, func(a, b status.SourceRow) int { return strings.Compare(a.ID, b.ID) })
	return out
}

func sortedChannels(in []status.ChannelRow) []status.ChannelRow {
	out := slices.Clone(in)
	slices.SortStableFunc(out, func(a, b status.ChannelRow) int { return strings.Compare(a.Name, b.Name) })
	return out
}

