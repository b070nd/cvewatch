// WriteJSON writes the pack as indented JSON.
func (p Pack) WriteJSON(w io.Writer) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(p)
}

// WriteMarkdown writes the pack as a markdown report. All feed and user text
// is escaped so it cannot add markup, links, table cells or HTML.
func (p Pack) WriteMarkdown(w io.Writer) error {
	var b bytes.Buffer
	pf := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	pf("# Evidence pack: %s\n\n", esc(p.ID))
	if len(p.Aliases) > 0 {
		aliases := make([]string, len(p.Aliases))
		for i, a := range p.Aliases {
			aliases[i] = esc(a)
		}
		pf("Also known as: %s\n\n", strings.Join(aliases, ", "))
	}

	pf("| Field | Value |\n|---|---|\n")
	pf("| Title (feed text, untrusted) | %s |\n", orDash(esc(p.Untrusted.Title)))
	pf("| Severity | %s |\n", esc(string(p.Severity)))
	pf("| Published | %s |\n", ts(p.Published))
	pf("| Known exploited (CISA KEV) | %s |\n", kevText(p.KEV))
	pf("| Fix known | %s |\n", fixText(p.Fixes))
	pf("| Articles | %d |\n", p.Untrusted.Articles)
	pf("| Audit trail intact | %s |\n", auditText(p))

	pf("\n## Environments\n\n")
	if len(p.Matrix) == 0 {
		pf("No findings recorded.\n")
	} else {
		pf("| Project | Env | Status | Version verdict | Installed | Owner | Due | Ticket | Note |\n|---|---|---|---|---|---|---|---|---|\n")
		for _, r := range p.Matrix {
			inst := make([]string, len(r.Installed))
			for i, s := range r.Installed {
				inst[i] = esc(s)
			}
			pf("| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				orDash(esc(r.Project)), orDash(esc(r.Env)), esc(string(r.Status)), verdict(r.Applies),
				orDash(strings.Join(inst, ", ")), orDash(esc(r.Owner)), ts(r.Due), orDash(esc(r.Ticket)), orDash(esc(r.Note)))
		}
	}

	pf("\n## Timeline\n\n")
	if len(p.Timeline) == 0 {
		pf("No dated events recorded.\n")
	}
	for _, e := range p.Timeline {
		line := fmt.Sprintf("- %s **%s** %s", ts(e.Time), esc(e.Kind), esc(e.Detail))
		if e.Actor != "" {
			line += " (by " + esc(query.ActorLabel(e.Actor)) + ")"
		}
		if e.URL != "" {
			line += " " + code(e.URL)
		}
		pf("%s [%s]\n", line, esc(e.Source))
	}

	pf("\n## Evidence\n\n")
	found := false
	for _, r := range p.Matrix {
		if len(r.Evidence) == 0 {
			continue
		}
		found = true
		pf("### %s / %s\n\n", esc(r.Project), esc(r.Env))
		for _, e := range r.Evidence {
			line := fmt.Sprintf("- %s %s", ts(e.Time), orDash(esc(e.Actor)))
			if e.Note != "" {
				line += ": " + esc(e.Note)
			}
			if e.URL != "" {
				line += " " + code(e.URL)
			}
			pf("%s\n", line)
		}
		pf("\n")
	}
	if !found {
		pf("No evidence attached.\n\n")
	}

	pf("---\n\nGenerated by cvewatch at %s, schema version %d\n", ts(p.GeneratedAt), p.SchemaVersion)

	_, err := w.Write(b.Bytes())
	return err
}

func kevText(k *model.KEV) string {
	if k == nil {
		return "no"
	}
	s := "yes, added " + ts(k.DateAdded) + ", due " + ts(k.DueDate)
	if k.Ransomware {
		s += ", known ransomware use"
	}
	return s
}

func fixText(fs []model.Fix) string {
	if len(fs) == 0 {
		return "no"
	}
	for _, f := range fs {
		if f.Official {
			return "yes (official)"
		}
	}
	return "yes (unofficial sources only)"
}

func auditText(p Pack) string {
	if p.AuditIntact {
		if p.AuditNote != "" {
			return "yes (" + esc(p.AuditNote) + ")"
		}
		return "yes"
	}
	if p.AuditNote != "" {
		return "no: " + esc(p.AuditNote)
	}
	return "no"
}

func verdict(a model.Applicability) string {
	switch a {
	case model.AppAffected:
		return "affected"
	case model.AppNotAffected:
		return "not affected"
	}
	return "unknown"
}

func ts(t time.Time) string {
	if t.IsZero() {
		return "-"
	}
	return t.UTC().Format(time.RFC3339)
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// esc makes untrusted text safe to put in a markdown line or table cell:
// control characters are dropped, whitespace becomes single spaces, markup
// characters are backslash-escaped or written as entities.
func esc(s string) string {
	var b strings.Builder
	space := false
	for _, r := range s {
		switch {
		case unicode.IsSpace(r):
			space = true
			continue
		case unicode.IsControl(r) || unicode.Is(unicode.Cf, r):
			continue
		}
		if space && b.Len() > 0 {
			b.WriteByte(' ')
		}
		space = false
		switch r {
		case '<':
			b.WriteString("&lt;")
		case '>':
			b.WriteString("&gt;")
		case '&':
			b.WriteString("&amp;")
		case '\\', '`', '*', '_', '[', ']', '!', '~', '|', '#':
			b.WriteByte('\\')
			b.WriteRune(r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// code renders an untrusted URL as an inert code span, never as a link.
// Characters that could end the span, the table cell or open a tag are
// percent-encoded.
func code(u string) string {
	var b strings.Builder
	for _, r := range u {
		switch {
		case unicode.IsSpace(r):
			b.WriteString("%20")
		case unicode.IsControl(r) || unicode.Is(unicode.Cf, r):
		case r == '`':
			b.WriteString("%60")
		case r == '<':
			b.WriteString("%3C")
		case r == '>':
			b.WriteString("%3E")
		case r == '|':
			b.WriteString("%7C")
		default:
			b.WriteRune(r)
		}
	}
	return "`" + b.String() + "`"
}
